#!/bin/bash
# Install/refresh the watcher: notifier, tagged system units + their scripts, polkit rule for `watcher run`.
# Re-run this after adding or changing any watched SYSTEM unit. Run in a real terminal: ~/.config/watcher/install.sh
set -euo pipefail
W="$HOME/.config/watcher/system"

echo "▶ notifier, pause gate, fixer"
for f in watcher-notify watcher-gate watcher-fix watcher-alert; do
    sudo install -m 755 -o root -g root "$W/$f" /usr/local/bin/$f
done
sudo install -m 644 "$W/watcher-notify@.service" "$W/watcher-verify.service" /etc/systemd/system/

echo "▶ watched system units + scripts (from their source folders)"
sudo install -m 755 -o root -g root "$HOME/.config/backup/system/system-backup" /usr/local/bin/system-backup
sudo install -m 755 -o root -g root "$HOME/.config/update/system/system-update" /usr/local/bin/system-update
sudo install -m 644 "$HOME/.config/backup/system/system-backup.service" \
    "$HOME/.config/update/system/system-update.service" \
    "$HOME/.config/update/system/nightly-maintenance.service" /etc/systemd/system/

echo "▶ disk-health job"
sudo install -m 755 -o root -g root "$HOME/.config/disk-health/system/disk-health" /usr/local/bin/disk-health
sudo install -m 644 "$HOME/.config/disk-health/system/disk-health.service" "$HOME/.config/disk-health/system/disk-health.timer" /etc/systemd/system/

echo "▶ snapper timers → watcher (drop-ins; only if snapshots are set up)"
if rpm -q snapper >/dev/null 2>&1; then
    for u in timeline cleanup; do
        sudo install -d /etc/systemd/system/snapper-$u.service.d
        sudo install -m 644 "$HOME/.config/snapshots/system/snapper-$u-watcher.conf" /etc/systemd/system/snapper-$u.service.d/watcher.conf
    done
fi

echo "▶ removing retired system-backup.timer (nightly-maintenance.timer replaced it)"
sudo systemctl disable --now system-backup.timer 2>/dev/null || true
sudo rm -f /etc/systemd/system/system-backup.timer

echo "▶ polkit: let $USER start/stop/restart every watched system unit"
units=$( { grep -l '^X-Watcher-Name=' /etc/systemd/system/*.service | xargs -n1 basename
            grep -l '^X-Watcher-Name=' /etc/systemd/system/*.service.d/*.conf 2>/dev/null | xargs -rn1 dirname | xargs -rn1 basename | sed 's/\.d$//'
          } | sort -u | sed 's/.*/"&"/' | paste -sd, -)
sudo tee /etc/polkit-1/rules.d/50-watcher.rules >/dev/null <<RULE
// generated by ~/.config/watcher/install.sh — watched system units $USER may start/stop/restart without a password
polkit.addRule(function(action, subject) {
    var units = [$units];
    if (action.id == "org.freedesktop.systemd1.manage-units" &&
        units.indexOf(action.lookup("unit")) >= 0 &&
        ["start", "stop", "restart"].indexOf(action.lookup("verb")) >= 0 &&
        subject.user == "$USER") {
        return polkit.Result.YES;
    }
});
RULE

sudo restorecon -R /usr/local/bin /etc/systemd/system /etc/polkit-1/rules.d
sudo systemctl daemon-reload
systemctl --user daemon-reload
sudo systemctl enable --now disk-health.timer
echo "✔ watcher installed — try: watcher"
